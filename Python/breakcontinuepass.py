#BREAK statement
for i in range(1, 14):
    print(i)
    if i == 8:
        break         # it breaks at 8
print("End of Programe")

#Continue statement
for i in range (0,8):
    print(i)
    if i == 5:
        continue     # it continue till 7
print("end of programe")

# pass statement
for i in range (0, 9):
    print(i)
    if i == 7:
        pass   # it's do nothing. its just a sytax
print("end of programe")
